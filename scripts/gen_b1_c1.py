def slug(word: str) -> str:
    s = word.lower()
    for a, b in {
        "ä": "ae", "ö": "oe", "ü": "ue", "ß": "ss",
        " ": "_", "-": "_", ".": "", "/": "_",
    }.items():
        s = s.replace(a, b)
    s = re.sub(r"[^a-z0-9_]+", "", s)
    return (s[:48] or "w")

def entry(article, word, plural, zh, cat, level, example=None, example_zh=None):
    art = None if article in (None, "-", "") else article
    pl = None if plural in (None, "-", "") else plural
    if example is None:
        if art:
            example = f"{art.capitalize()} {word} ist auf {level}-Niveau wichtig."
            example_zh = f"{art} {word}（{zh}）在 {level} 程度很重要。"
        elif cat == "動詞":
            example = f"Kannst du {word}?"
            example_zh = f"你會「{word}」（{zh}）嗎？"
        elif cat == "形容詞":
            example = f"Das ist sehr {word}."
            example_zh = f"那非常{zh}。"
        else:
            example = f"Was bedeutet {word}?"
            example_zh = f"{word} 的意思是「{zh}」。"
    return {
        "id": slug(word) + "_" + level.lower(),
        "article": art,
        "word": word,
        "translation": zh,
        "phonetic": word,
        "category": cat,
        "example": example,
        "exampleTranslation": example_zh,
        "level": level,
        **({"plural": pl} if pl else {}),
    }

