def build_level(level, nouns, verbs, adjs):
    out = []
    for row in nouns:
        out.append(entry(*row, level))
    for word, zh in verbs:
        out.append(entry(None, word, None, zh, "動詞", level))
    for word, zh in adjs:
        out.append(entry(None, word, None, zh, "形容詞", level))
    return out

def main():
    existing = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    # drop any previous B1/B2/C1 to allow re-run
    base = [w for w in existing if w.get("level") in ("A1", "A2")]
    seen = {(w["word"].lower(), w["level"], w.get("article")) for w in base}

    added = []
    for chunk in [
        build_level("B1", B1_NOUNS, B1_VERBS, B1_ADJ),
        build_level("B2", B2_NOUNS, B2_VERBS, B2_ADJ),
        build_level("C1", C1_NOUNS, C1_VERBS, C1_ADJ),
    ]:
        for w in chunk:
            key = (w["word"].lower(), w["level"], w.get("article"))
            if key in seen:
                continue
            # unique id
            wid = w["id"]
            n = 2
            ids = {x["id"] for x in base} | {x["id"] for x in added}
            while wid in ids:
                wid = f"{w['id']}_{n}"
                n += 1
            w["id"] = wid
            seen.add(key)
            added.append(w)

    merged = base + added
    counts = {}
    for w in merged:
        counts[w["level"]] = counts.get(w["level"], 0) + 1
    JSON_PATH.write_text(json.dumps(merged, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("counts", counts, "total", len(merged), "added", len(added))

if __name__ == "__main__":
    main()
